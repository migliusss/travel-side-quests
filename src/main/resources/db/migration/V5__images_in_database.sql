-- Image bytes live in Postgres rather than an object store. One less service to run,
-- and nothing to reconcile between the database and a bucket.
--
-- The bytes sit in their own table so that listing side quests never drags them along:
-- a page of twelve cards would otherwise pull every full-size photo through Hibernate.

ALTER TABLE side_quest_image
    DROP CONSTRAINT side_quest_image_source_check,
    DROP CONSTRAINT side_quest_image_storage_key_key,
    DROP COLUMN storage_key,
    ADD COLUMN content_type VARCHAR(100);

CREATE TABLE side_quest_image_content (
    image_id BIGINT PRIMARY KEY
        REFERENCES side_quest_image(id) ON DELETE CASCADE,

    content BYTEA NOT NULL
);


-- Uploads arrive before the submission that references them, so they wait here until
-- the form is sent. Rows the submitter abandons are swept on later uploads.
CREATE TABLE image_upload (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    storage_key UUID NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    content BYTEA NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX image_upload_created_at_idx ON image_upload (created_at);
