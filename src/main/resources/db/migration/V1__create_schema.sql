CREATE TABLE IF NOT EXISTS country (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    country_code VARCHAR(2) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS destination (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id BIGINT NOT NULL REFERENCES country(id),
    name VARCHAR(150) NOT NULL,
    type VARCHAR(50) NOT NULL CHECK (
        type IN (
                 'CITY',
                 'TOWN',
                 'REGION',
                 'NEIGHBORHOOD',
                 'NATIONAL_PARK',
                 'ISLAND',
                 'MOUNTAIN_RANGE',
                 'COASTLINE',
                 'OTHER'
        )
    )
);

CREATE TABLE IF NOT EXISTS side_quest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id BIGINT NOT NULL REFERENCES destination(id),
    name VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    address VARCHAR(300),
    latitude DECIMAL(9,7) NOT NULL,
    longitude DECIMAL(9,7) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS side_quest_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    side_quest_id BIGINT NOT NULL REFERENCES side_quest(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    alt_text VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS category_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS side_quest_category (
    side_quest_id BIGINT NOT NULL REFERENCES side_quest(id),
    category_id BIGINT NOT NULL REFERENCES category_type(id),

    PRIMARY KEY (side_quest_id, category_id)
);

CREATE TABLE IF NOT EXISTS source_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS side_quest_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    side_quest_id BIGINT NOT NULL REFERENCES side_quest(id) ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    source_type_id BIGINT NOT NULL REFERENCES source_type(id),
    url TEXT,
    author VARCHAR(200),
    page_number TEXT
);